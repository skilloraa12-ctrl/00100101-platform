const SLANG_MAP = [
  [/\bшо\b/g, 'що'],
  [/\bчо\b/g, 'чому'],
  [/непон\w*/g, 'не поняла'],
  [/незрозум\w*/g, 'не зрозуміла'],
  [/незна\w*/g, 'не знаю'],
  [/ненаю/g, 'не знаю'],
  [/непрацює/g, 'не працює'],
  [/нєпон\w*/g, 'не поняла'],
]

export function normalizeText(raw) {
  let t = (raw || '').toLowerCase().trim()
  t = t.replace(/[.,!?;:()«»"'\-–—]/g, ' ')
  t = t.replace(/(.)\1{2,}/g, '$1$1')
  for (const [pattern, replacement] of SLANG_MAP) t = t.replace(pattern, replacement)
  t = t.replace(/\s+/g, ' ').trim()
  return t
}

function tokens(text) {
  return (text.match(/[\p{L}\p{N}]+/gu) || []).filter((w) => w.length > 1)
}

const CRY_EMOJI = /😭|😵|🥲|💀|😩|😫|🙏/
export function isWordless(raw) {
  const t = (raw || '').trim()
  if (!t) return false
  const hasLetters = /[\p{L}]/u.test(t)
  if (hasLetters) {
    const words = normalizeText(t)
    return ['що', 'ааа', 'допоможіть', 'рятуйте', 'капець', 'все', 'help'].includes(words)
  }
  return CRY_EMOJI.test(t) || /^[?!.\s]+$/.test(t)
}

