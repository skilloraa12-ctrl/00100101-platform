const SHORT_FOLLOWUPS = {
  'що': 'what_is_this', 'навіщо': 'why_is_this_needed', 'як': 'how_to_code',
  'де': 'how_to_code', 'чому': 'why_is_this_needed', 'приклад': 'example',
  'ще': 'repeat_remind', 'повтори': 'repeat_remind', 'простіше': 'lesson_not_understood',
  'правильно': 'check_my_work', 'далі': 'what_next',
}

export function classifyIntent(rawText, context = {}) {
  const norm = normalizeText(rawText)
  if (!norm) return null

  const words = tokens(norm)
  if (words.length <= 2 && SHORT_FOLLOWUPS[norm]) {
    const id = context.lastIntentId || SHORT_FOLLOWUPS[norm]
    const def = INTENTS.find((i) => i.id === id) || INTENTS.find((i) => i.id === SHORT_FOLLOWUPS[norm])
    return def ? { intentId: def.id, isMeta: def.isMeta } : null
  }

  let best = null
  let bestScore = 0
  for (const intent of INTENTS) {
    let score = 0
    for (const trig of intent.triggers) {
      if (norm.includes(trig)) score += trig.split(' ').length >= 2 ? 3 : 1
    }
    if (score > bestScore) { bestScore = score; best = intent }
  }

  if (!best || bestScore < 2) return null
  return { intentId: best.id, isMeta: best.isMeta }
}

